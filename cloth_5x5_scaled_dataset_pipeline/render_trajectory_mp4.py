"""Render cached 5x5 cloth reference trajectories to MP4 files.

Example:
    python render_trajectory_mp4.py

By default this reads:
    scaled_data/_trajectory_cache/65012d321d

and writes one MP4 per cached boundary/motion trajectory to:
    scaled_data/trajectory_mp4

The output directory mirrors the cache layout. For example:
    scaled_data/_trajectory_cache/65012d321d/boundary_xxx/motion_yyy.pt

becomes:
    scaled_data/trajectory_mp4/65012d321d/boundary_xxx/motion_yyy.mp4
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

try:
    import imageio.v2 as imageio
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    import torch
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
except ImportError as exc:  # pragma: no cover - dependency guard for CLI use.
    raise SystemExit(
        "Missing render dependency. Run this script in the project environment "
        "with torch, numpy, matplotlib, imageio, and an MP4 writer available "
        "(for imageio this is usually imageio-ffmpeg). "
        f"Original import error: {exc}"
    ) from exc

from cloth_scale_common import NUM_PARTICLES, SPRING_EDGES, TRIANGLE_FACES


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_CACHE_DIR = SCRIPT_DIR / "scaled_data" / "_trajectory_cache" / "65012d321d"
DEFAULT_OUTPUT_DIR = SCRIPT_DIR / "scaled_data" / "trajectory_mp4"
STATE_FIELDS = ("exact_y", "current_y", "q", "fixed_target")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--field",
        choices=STATE_FIELDS,
        default="exact_y",
        help="State sequence to render. exact_y is the solved reference trajectory.",
    )
    parser.add_argument("--fps", type=int, default=12)
    parser.add_argument("--dpi", type=int, default=140)
    parser.add_argument("--stride", type=int, default=1, help="Render every Nth cached frame.")
    parser.add_argument("--limit", type=int, default=None, help="Render only the first N trajectories.")
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--draw-springs", action="store_true", help="Draw spring edges on top of faces.")
    parser.add_argument("--no-faces", action="store_true", help="Only draw vertices and optional springs.")
    parser.add_argument("--elev", type=float, default=25.0)
    parser.add_argument("--azim", type=float, default=-55.0)
    parser.add_argument("--figsize", type=float, nargs=2, default=(6.4, 5.6), metavar=("W", "H"))
    return parser.parse_args()


def natural_key(path: Path) -> tuple[Any, ...]:
    return tuple(int(x) if x.isdigit() else x for x in re.split(r"(\d+)", str(path)))


def output_path_for(cache_file: Path, cache_dir: Path, output_dir: Path) -> Path:
    relative = cache_file.relative_to(cache_dir)
    mirrored = output_dir / cache_dir.name / relative
    return mirrored.with_suffix(".mp4")


def load_positions(cache_file: Path, field: str, stride: int) -> tuple[np.ndarray, dict[str, Any]]:
    # Local project cache files are trusted inputs generated by build_scaled_datasets.py.
    try:
        data = torch.load(cache_file, map_location="cpu", weights_only=False)
    except TypeError:
        data = torch.load(cache_file, map_location="cpu")
    records = data.get("records")
    if not isinstance(records, dict):
        raise ValueError(f"{cache_file} does not contain a records dict")
    if field not in records:
        raise ValueError(f"{cache_file} has no records['{field}']; available keys: {sorted(records)}")

    states = records[field]
    if states.ndim != 2 or states.shape[1] != NUM_PARTICLES * 3:
        raise ValueError(f"{cache_file} records['{field}'] has unexpected shape {tuple(states.shape)}")
    if stride < 1:
        raise ValueError("--stride must be >= 1")

    positions = states[::stride].reshape(-1, NUM_PARTICLES, 3).detach().cpu().numpy()
    meta = {
        "schema_version": data.get("schema_version"),
        "total_steps": int(data.get("total_steps", positions.shape[0])),
        "boundary": data.get("boundary", {}),
        "motion": data.get("motion", {}),
        "warnings": data.get("warnings", []),
    }
    return positions, meta


def equal_axis_limits(points: np.ndarray) -> tuple[tuple[float, float], tuple[float, float], tuple[float, float]]:
    mins = points.reshape(-1, 3).min(axis=0)
    maxs = points.reshape(-1, 3).max(axis=0)
    center = 0.5 * (mins + maxs)
    radius = float(np.max(maxs - mins) * 0.55)
    radius = max(radius, 0.25)
    return tuple((float(c - radius), float(c + radius)) for c in center)  # type: ignore[return-value]


def render_mp4(
    *,
    positions: np.ndarray,
    meta: dict[str, Any],
    output_path: Path,
    fps: int,
    dpi: int,
    figsize: tuple[float, float],
    elev: float,
    azim: float,
    draw_faces: bool,
    draw_springs: bool,
) -> None:
    if positions.shape[0] == 0:
        raise ValueError("No frames to render")

    xlim, ylim, zlim = equal_axis_limits(positions)
    faces = np.asarray(TRIANGLE_FACES, dtype=np.int64)
    edges = np.asarray(SPRING_EDGES, dtype=np.int64)
    fixed_indices = tuple(int(x) for x in meta.get("boundary", {}).get("fixed_indices", ()))

    fig = plt.figure(figsize=figsize, dpi=dpi)
    ax = fig.add_subplot(111, projection="3d")
    fig.patch.set_facecolor("white")

    boundary = meta.get("boundary", {})
    motion = meta.get("motion", {})
    title = (
        f"boundary {boundary.get('index', '?')}: {boundary.get('name', '?')}\n"
        f"motion {motion.get('index', '?')}: {motion.get('name', '?')}"
    )

    try:
        try:
            writer_context = imageio.get_writer(
                str(output_path),
                format="FFMPEG",
                mode="I",
                fps=fps,
                codec="libx264",
                quality=8,
                macro_block_size=8,
            )
        except Exception as exc:
            raise RuntimeError(
                "Could not create an FFMPEG MP4 writer. Make sure imageio-ffmpeg "
                "or a system ffmpeg binary is available in this conda environment."
            ) from exc

        with writer_context as writer:
            for frame_index, points in enumerate(positions):
                ax.clear()
                ax.set_title(title, fontsize=9)
                ax.set_xlim(*xlim)
                ax.set_ylim(*ylim)
                ax.set_zlim(*zlim)
                ax.set_xlabel("x")
                ax.set_ylabel("y")
                ax.set_zlabel("z")
                ax.view_init(elev=elev, azim=azim)
                ax.set_box_aspect((1, 1, 1))
                ax.grid(True, linewidth=0.4, alpha=0.35)

                if draw_faces:
                    face_collection = Poly3DCollection(
                        points[faces],
                        alpha=0.55,
                        facecolor="#72a6c9",
                        edgecolor="#2f566f",
                        linewidth=0.45,
                    )
                    ax.add_collection3d(face_collection)

                if draw_springs:
                    for a, b in edges:
                        seg = points[[a, b]]
                        ax.plot(seg[:, 0], seg[:, 1], seg[:, 2], color="#2f566f", linewidth=0.7, alpha=0.9)

                ax.scatter(points[:, 0], points[:, 1], points[:, 2], s=14, color="#1f4f6b", depthshade=True)
                if fixed_indices:
                    fixed = points[list(fixed_indices)]
                    ax.scatter(fixed[:, 0], fixed[:, 1], fixed[:, 2], s=34, color="#d1495b", depthshade=True)

                ax.text2D(0.02, 0.02, f"frame {frame_index + 1}/{positions.shape[0]}", transform=ax.transAxes, fontsize=8)
                fig.canvas.draw()
                rgba = np.asarray(fig.canvas.buffer_rgba())
                writer.append_data(rgba[:, :, :3])
    finally:
        plt.close(fig)


def write_manifest(rows: list[dict[str, Any]], output_dir: Path) -> None:
    manifest_path = output_dir / "render_manifest.json"
    with manifest_path.open("w", encoding="utf-8") as f:
        json.dump(rows, f, indent=2, ensure_ascii=False)


def main() -> None:
    args = parse_args()
    cache_dir = args.cache_dir.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    cache_files = sorted(cache_dir.glob("boundary_*/*.pt"), key=natural_key)
    if args.limit is not None:
        cache_files = cache_files[: args.limit]
    if not cache_files:
        raise SystemExit(f"No trajectory cache files found under {cache_dir}")

    rows: list[dict[str, Any]] = []
    for idx, cache_file in enumerate(cache_files, start=1):
        out_path = output_path_for(cache_file, cache_dir, output_dir)
        if out_path.exists() and not args.overwrite:
            print(f"[{idx}/{len(cache_files)}] skip existing {out_path.relative_to(output_dir)}")
            rows.append({"cache_file": str(cache_file), "mp4": str(out_path), "status": "skipped_existing"})
            continue

        out_path.parent.mkdir(parents=True, exist_ok=True)
        print(
            f"[{idx}/{len(cache_files)}] render "
            f"{cache_file.relative_to(cache_dir)} -> {out_path.relative_to(output_dir)}"
        )
        try:
            positions, meta = load_positions(cache_file, args.field, args.stride)
            render_mp4(
                positions=positions,
                meta=meta,
                output_path=out_path,
                fps=args.fps,
                dpi=args.dpi,
                figsize=tuple(float(x) for x in args.figsize),
                elev=args.elev,
                azim=args.azim,
                draw_faces=not args.no_faces,
                draw_springs=args.draw_springs,
            )
        except Exception as exc:
            rows.append({"cache_file": str(cache_file), "mp4": str(out_path), "status": "failed", "error": str(exc)})
            write_manifest(rows, output_dir)
            raise

        rows.append(
            {
                "cache_file": str(cache_file),
                "mp4": str(out_path),
                "status": "rendered",
                "field": args.field,
                "fps": args.fps,
                "stride": args.stride,
                "boundary": meta.get("boundary", {}),
                "motion": meta.get("motion", {}),
            }
        )
        write_manifest(rows, output_dir)

    write_manifest(rows, output_dir)
    print(f"Done. Wrote manifest: {output_dir / 'render_manifest.json'}")


if __name__ == "__main__":
    main()
